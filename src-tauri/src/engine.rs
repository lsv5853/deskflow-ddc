pub fn identity(dir: &Path) -> Result<String> {
    let path = dir.join("identity.pem");
    if !path.exists() {
        let pair = rcgen::generate_simple_self_signed(vec!["deskflow-ddc.local".into()])?;
        atomic_write(
            &path,
            format!("{}\n{}", pair.key_pair.serialize_pem(), pair.cert.pem()).as_bytes(),
        )?;
    }
    let text = std::fs::read_to_string(path)?;
    rcgen::KeyPair::from_pem(&text).context("引擎私钥损坏")?;
    // Extract the DER without depending on certificate subject or key algorithm.
    use base64::Engine;
    let cert = text
        .split("-----BEGIN CERTIFICATE-----")
        .nth(1)
        .context("缺少引擎证书")?
        .split("-----END CERTIFICATE-----")
        .next()
        .unwrap();
    rcgen::CertificateParams::from_ca_cert_pem(&format!(
        "-----BEGIN CERTIFICATE-----{cert}-----END CERTIFICATE-----"
    ))
    .context("引擎证书损坏")?;
    let der = base64::engine::general_purpose::STANDARD.decode(
        cert.chars()
            .filter(|c| !c.is_whitespace())
            .collect::<String>(),
    )?;
    Ok(hex::encode(Sha256::digest(der)))
}
fn ini(path: &str) -> String {
    format!("\"{}\"", path.replace('\\', "/").replace('"', "\\\""))
}
pub fn server_config(c: &Config, local: &str, peer: &str, peer_retained: bool) -> Result<String> {
    c.validate()?;
    uuid::Uuid::parse_str(local)?;
    uuid::Uuid::parse_str(peer)?;
    let (host, client) = if c.role == "host" {
        (local, peer)
    } else {
        (peer, local)
    };
    // With neither computer having a separate visible screen, no edge can
    // transfer input safely in manual-video mode. Explicit hotkeys still work.
    let side =
        if c.cross_screen_video == "manual" && c.retained_display_id.is_empty() && !peer_retained {
            "off"
        } else {
            c.layout_side.as_str()
        };
    let edges = match side {
        "left" => Some(("right", "left")),
        "right" => Some(("left", "right")),
        "top" => Some(("down", "up")),
        "bottom" => Some(("up", "down")),
        _ => None,
    };
    let mut text = format!("# Generated by Deskflow DDC.\nsection: links\n\tsb-{host}:");
    if let Some((out, _)) = edges {
        text += &format!("\n\t\t{out} = sb-{client}");
    }
    text += &format!("\n\tsb-{client}:");
    if let Some((_, back)) = edges {
        text += &format!("\n\t\t{back} = sb-{host}");
    }
    text += "\nend\nsection: options\n";
    let chord = |s: &str| {
        if crate::model::platform() == "darwin" {
            s.replace("alt", "super")
        } else {
            s.into()
        }
    };
    if c.cross_screen_video != "manual" && (edges.is_none() || c.cross_screen_video != "keep") {
        text += &format!("\tkeystroke({}) = switchToNextScreen\n", chord(&c.shortcut));
    }
    for (key, target) in [
        ("control+alt+Escape", host),
        ("control+alt+shift+F18", host),
        ("control+alt+shift+F19", client),
    ] {
        text += &format!(
            "\tkeystroke({}) = switchToScreen(sb-{target})\n",
            chord(key)
        );
    }
    text += "end\n";
    Ok(text)
}
fn computer_settings(c: &Config, local: &str, peer: &Identity, local_platform: &str) -> String {
    let (host, client, mode) = if c.role == "host" {
        (local.to_owned(), peer.id.to_string(), c.modifier_mapping)
    } else {
        (peer.id.to_string(), local.to_owned(), peer.modifier_mapping)
    };
    let (control, super_key) = if mode.swaps_between(local_platform, &peer.platform) {
        ("super", "ctrl")
    } else {
        ("ctrl", "super")
    };
    // Deskflow 1.27 reads per-computer modifiers from its general settings,
    // not the legacy `section: screens`. Only the receiver is remapped; the
    // provider's local keys and server-side switch shortcuts stay unchanged.
    format!(
        "[computer_sb-{host}]\nname=sb-{host}\n\n\
         [computer_sb-{client}]\nname=sb-{client}\nmodifierCtrl={control}\nmodifierSuper={super_key}\n"
    )
}
pub fn prepare(
    c: &Config,
    local: &str,
    peer: &Identity,
    dir: &Path,
    address: &str,
) -> Result<PathBuf> {
    c.ready()?;
    peer.validate()?;
    let root = dir.join("deskflow");
    let tls = root.join("tls");
    std::fs::create_dir_all(&tls)?;
    atomic_write(
        &tls.join("identity.pem"),
        &std::fs::read(dir.join("identity.pem"))?,
    )?;
    atomic_write(
        &tls.join(if c.role == "host" {
            "trusted-clients"
        } else {
            "trusted-servers"
        }),
        format!("v2:sha256:{}\n", peer.fingerprint).as_bytes(),
    )?;
    atomic_write(
        &root.join("server.conf"),
        server_config(c, local, &peer.id.to_string(), peer.retained_display)?.as_bytes(),
    )?;
    let mut text=format!("[core]\ncomputerName=sb-{local}\ncoreMode={}\nprocessMode=0\nport={}\ninterface=\npreventSleep=false\n\n[security]\ntlsEnabled=true\ncheckPeerFingerprints=true\ncertificate={}\n\n[client]\nremoteHost={}\n\n[server]\nexternalConfig=true\nexternalConfigFile={}\nenableClipboard={}\nclipboardSize={}\n\n[log]\nlevel=INFO\ntoFile=false\n\n",if c.role=="host"{2}else{1},c.deskflow_port,ini(&tls.join("identity.pem").to_string_lossy()),ini(address),ini(&root.join("server.conf").to_string_lossy()),c.clipboard,c.clipboard_megabytes);
    text += &computer_settings(c, local, peer, crate::model::platform());
    let settings = root.join("Deskflow.conf");
    atomic_write(&settings, text.as_bytes())?;
    Ok(settings)
}
pub fn namespace(dir: &Path) -> PathBuf {
    std::env::temp_dir().join(format!(
        "ddc-core-{}",
        &hex::encode(Sha256::digest(dir.to_string_lossy().as_bytes()))[..16]
    ))
}
#[cfg(unix)]
async fn connect_ipc(path: &Path) -> Result<tokio::net::UnixStream> {
    Ok(tokio::net::UnixStream::connect(path).await?)
}
#[cfg(windows)]
async fn connect_ipc(_path: &Path) -> Result<tokio::net::windows::named_pipe::NamedPipeClient> {
    Ok(tokio::net::windows::named_pipe::ClientOptions::new().open(r"\\.\pipe\deskflow-core")?)
}
async fn preflight(path: &Path) -> Result<()> {
    match tokio::time::timeout(Duration::from_secs(1), connect_ipc(path)).await {
        Ok(Ok(_)) => bail!("检测到仍在运行的 Deskflow 引擎，已阻止开始共享。删除旧应用不会结束其进程；请先退出旧版和独立 Deskflow，无法退出时请重启电脑。未接管该引擎"),
        Ok(Err(e)) => {
            let harmless = e.downcast_ref::<std::io::Error>().is_some_and(|e| {
                matches!(
                    e.kind(),
                    std::io::ErrorKind::NotFound | std::io::ErrorKind::ConnectionRefused
                )
            });
            ensure!(harmless, "无法检查已有引擎：{e}");
        }
        Err(_) => bail!("检查已有引擎超时"),
    }
    Ok(())
}
// This only opens known IPC endpoints to check ownership; it never sends a
// control command or terminates a process started by another application.
pub async fn assert_no_running_engine(dir: &Path) -> Result<()> {
    let root = std::env::temp_dir();
    let mut paths = vec![root.join("deskflow-core")];
    #[cfg(target_os = "macos")]
    {
        paths.push(namespace(dir).join("deskflow-core"));
        // Deleted/replaced .app bundles can leave an engine in the data tree.
        // Check both Electron and Tauri namespaces before starting any session.
        for entry in std::fs::read_dir(&root)? {
            let entry = entry?;
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if entry.file_type()?.is_dir()
                && (name.starts_with("sb-core-") || name.starts_with("ddc-core-"))
            {
                paths.push(entry.path().join("deskflow-core"));
            }
        }
    }
    #[cfg(not(target_os = "macos"))]
    let _ = dir;
    paths.sort();
    paths.dedup();
    for path in paths {
        preflight(&path).await?;
    }
    Ok(())
}
/// Separate emergency-hotkey watchdog process (P0-1).
///
/// The main app also registers the emergency hotkey through Tauri, but a
/// wedged engine can swallow input before the app sees it. This process
/// owns no engine state: it only watches for the chord and, on match,
/// kills the engine after re-verifying its identity (PID + kernel start
/// time on macOS, PID + start-time snapshot on Windows), then exits.
/// The session ending normally ends the watcher too (stdin lease on
/// macOS, parent liveness on Windows), so a clean quit never leaves a
/// live watcher behind. On other platforms there is no separate watcher;
/// the in-app Tauri shortcut and the peer-side stop remain the channels.
pub struct EmergencyWatch {
    child: Option<Child>,
    lease: Option<tokio::process::ChildStdin>,
}
impl EmergencyWatch {
    #[cfg(target_os = "macos")]
    pub async fn start(
        engine_pid: u32,
        hotkey: &str,
        resources: &Path,
        _app_pid: u32,
    ) -> Result<Option<Self>> {
        // Exact kernel start time, same source as the exit-protection
        // guardian: a recycled PID can never match it.
        let (secs, micros) = crate::engine_guard::engine_start_time(engine_pid)?;
        let mut command = Command::new(resources.join("native/bin/mac-hotkey"));
        command
            .args([
                "watch",
                &engine_pid.to_string(),
                &secs.to_string(),
                &micros.to_string(),
                hotkey,
            ])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .kill_on_drop(true);
        let mut child = command.spawn().context("无法启动紧急停止监听")?;
        // Ready handshake, mirroring the guardian: a watcher whose tap
        // never installs (for example missing accessibility permission)
        // must not silently pretend to cover the session.
        let output = child.stdout.take().context("紧急停止监听确认通道不可用")?;
        let mut lines = tokio::io::BufReader::new(output).lines();
        let ready = tokio::time::timeout(
            Duration::from_secs(3),
            lines.next_line(),
        )
        .await;
        if !matches!(ready, Ok(Ok(Some(ref line))) if line == "ready") {
            let _ = child.kill().await;
            anyhow::bail!("紧急停止监听未就绪");
        }
        let lease = child.stdin.take();
        Ok(Some(Self {
            child: Some(child),
            lease,
        }))
    }
    #[cfg(target_os = "windows")]
    pub async fn start(
        engine_pid: u32,
        hotkey: &str,
        resources: &Path,
        app_pid: u32,
    ) -> Result<Option<Self>> {
        let mut command = Command::new("powershell.exe");
        command
            .args([
                "-NoProfile",
                "-NonInteractive",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
            ])
            .arg(resources.join("native/monitor.ps1"))
            .args([
                "-Action",
                "watch",
                "-EnginePid",
                &engine_pid.to_string(),
                "-AppPid",
                &app_pid.to_string(),
                "-Hotkey",
                hotkey,
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .creation_flags(0x08000000)
            .kill_on_drop(true);
        let child = command.spawn().context("无法启动紧急停止监听")?;
        Ok(Some(Self {
            child: Some(child),
            lease: None,
        }))
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    pub async fn start(
        _engine_pid: u32,
        _hotkey: &str,
        _resources: &Path,
        _app_pid: u32,
    ) -> Result<Option<Self>> {
        Ok(None)
    }
    /// End the watcher. Closing the stdin lease lets a macOS watcher exit
    /// on its own; a leftover process is killed after a short grace.
    pub async fn finish(mut self) {
        drop(self.lease.take());
        if let Some(mut child) = self.child.take() {
            if tokio::time::timeout(Duration::from_secs(2), child.wait())
                .await
                .is_err()
            {
                let _ = child.kill().await;
            }
        }
    }
}
pub struct Engine {
    pid: u32,
    guardian_pid: Option<u32>,
    emergency_watch_active: bool,
    stop: mpsc::Sender<oneshot::Sender<Result<()>>>,
    task: tokio::task::JoinHandle<()>,
}
impl Engine {
    pub async fn start(
        binary: PathBuf,
        c: &Config,
        settings: &Path,
        dir: &Path,
        resources: &Path,
        events: mpsc::Sender<Event>,
    ) -> Result<Self> {
        let temp = namespace(dir);
        std::fs::create_dir_all(&temp)?;
        assert_no_running_engine(dir).await?;
        let ipc = if cfg!(target_os = "macos") {
            temp.join("deskflow-core")
        } else {
            std::env::temp_dir().join("deskflow-core")
        };
        if c.role == "host" {
            drop(
                tokio::net::TcpListener::bind(("0.0.0.0", c.deskflow_port))
                    .await
                    .context("键鼠端口已被占用")?,
            );
        }
        let mut command = Command::new(binary);
        command
            .arg(if c.role == "host" { "server" } else { "client" })
            .args(["--settings"])
            .arg(settings)
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true);
        if cfg!(target_os = "macos") {
            command.env("TMPDIR", format!("{}/", temp.display()));
        }
        command
            .env("XDG_CONFIG_HOME", dir.join("isolated-config"))
            .env("XDG_STATE_HOME", dir.join("isolated-state"));
        #[cfg(windows)]
        command.creation_flags(0x08000000);
        let mut child = command.spawn().context("无法启动内置键鼠引擎")?;
        let pid = child.id().context("无法获取键鼠引擎进程 ID")?;
        #[cfg(target_os = "macos")]
        let mut guardian = {
            let result = async {
                crate::engine_guard::Guardian::start(&mut child, &std::env::current_exe()?).await
            }
            .await;
            match result {
                Ok(guardian) => guardian,
                Err(error) => {
                    child.kill().await.context("退出保护失败且无法结束引擎")?;
                    return Err(error);
                }
            }
        };
        #[cfg(target_os = "macos")]
        let guardian_pid = guardian.pid();
        #[cfg(not(target_os = "macos"))]
        let guardian_pid = None;
        // Best-effort: if the separate watcher cannot start (for example
        // a dev build without the native helper), the session still
        // starts and the in-app Tauri shortcut remains available. The
        // caller logs the degraded state.
        let emergency_watch = match EmergencyWatch::start(
            pid,
            &c.emergency_shortcut,
            resources,
            std::process::id(),
        )
        .await
        {
            Ok(watch) => watch,
            Err(_) => None,
        };
        let emergency_watch_active = emergency_watch.is_some();
        for pipe in [
            child
                .stdout
                .take()
                .map(|s| Box::new(s) as Box<dyn tokio::io::AsyncRead + Unpin + Send>),
            child
                .stderr
                .take()
                .map(|s| Box::new(s) as Box<dyn tokio::io::AsyncRead + Unpin + Send>),
        ]
        .into_iter()
        .flatten()
        {
            let tx = events.clone();
            tokio::spawn(async move {
                let mut framed = tokio_util::codec::FramedRead::new(
                    pipe,
                    tokio_util::codec::LinesCodec::new_with_max_length(16384),
                );
                use futures_util::StreamExt;
                while let Some(Ok(line)) = framed.next().await {
                    if !line.contains("DEBUG")
                        && !line.contains("VERBOSE")
                        && !line.to_lowercase().contains("clipboard")
                    {
                        if tx.send(Event::Output(line)).await.is_err() {
                            break;
                        }
                    }
                }
            });
        }
        let (ipc_stop, mut ipc_rx) = mpsc::channel::<()>(1);
        let tx = events.clone();
        let ipc_task = tokio::spawn(async move {
            for _ in 0..72 {
                match connect_ipc(&ipc).await {
                    Ok(socket) => {
                        use futures_util::StreamExt;
                        let (read, mut write) = tokio::io::split(socket);
                        let mut lines = tokio_util::codec::FramedRead::new(
                            read,
                            tokio_util::codec::LinesCodec::new_with_max_length(65536),
                        );
                        let mut ready = false;
                        if write
                            .write_all(b"hello=screenbridge-probe\n")
                            .await
                            .is_err()
                        {
                            break;
                        }
                        // P0-1 heartbeat source: re-send the exact
                        // handshake already used at connect. A healthy
                        // engine answers with a `hello=` line, which the
                        // session loop counts as heartbeat activity for
                        // the watchdog. No new protocol is invented here;
                        // if a future Deskflow build stops answering,
                        // raise the timeout or set it to 0 (hotkey only).
                        let mut probe = tokio::time::interval(Duration::from_secs(
                            emergency::EMERGENCY_PROBE_INTERVAL_SECS,
                        ));
                        probe.tick().await;
                        loop {
                            tokio::select! {
                                _ = probe.tick() => {
                                    if write.write_all(b"hello=screenbridge-probe\n").await.is_err() {
                                        break;
                                    }
                                },
                                line = lines.next() => {
                                    let Some(Ok(line)) = line else { break };
                                    if let Some(version)=line.strip_prefix("versionMismatch=") {
                                        if version.len()>256 || version.contains(['\r','\n']) { break; }
                                        if write.write_all(format!("hello={version}\n").as_bytes()).await.is_err() { break; }
                                    }
                                    if line.starts_with("hello=") { ready=true; }
                                    if tx.send(Event::Ipc(line)).await.is_err() { return; }
                                },
                                stop = ipc_rx.recv() => {
                                    if stop.is_some() && ready { let _=write.write_all(b"stop\n").await; }
                                    return;
                                }
                            }
                        }
                    }
                    Err(_) => tokio::time::sleep(Duration::from_millis(250)).await,
                }
            }
            let _ = tx.send(Event::Ipc("observerDisconnected".into())).await;
        });
        let (stop, mut rx) = mpsc::channel::<oneshot::Sender<Result<()>>>(1);
        let mut emergency_watch = emergency_watch;
        let task = tokio::spawn(async move {
            let guard_failed = async {
                #[cfg(target_os = "macos")]
                let _ = guardian.wait().await;
                #[cfg(not(target_os = "macos"))]
                std::future::pending::<()>().await;
            };
            let reason = tokio::select! {
             result=child.wait()=>format!("{result:?}"),
             _=guard_failed=>{
              let _=stop_child(&mut child).await;
              "引擎退出保护意外结束，已停止共享".to_string()
             },
             request=rx.recv()=>{
              let _=ipc_stop.send(()).await;
              let result=stop_child(&mut child).await;
              let reason=if result.is_ok(){"stopped".to_string()}else{format!("{result:?}")};
              if let Some(reply)=request{let _=reply.send(result);}
              reason
             }
            };
            ipc_task.abort();
            #[cfg(target_os = "macos")]
            guardian.finish().await;
            // Normal session end ends the emergency watcher too: the
            // stdin lease closes (macOS) or the parent check fires
            // (Windows), and leftovers are killed after a grace period.
            if let Some(watch) = emergency_watch.take() {
                watch.finish().await;
            }
            // Deliver the exit event even under backpressure, independently of
            // the completed child/guardian cleanup awaited by application quit.
            tokio::spawn(async move {
                let _ = events.send(Event::Exited(reason)).await;
            });
        });
        Ok(Self {
            pid,
            guardian_pid,
            emergency_watch_active,
            stop,
            task,
        })
    }
    pub fn pid(&self) -> u32 {
        self.pid
    }
    pub fn emergency_watch_active(&self) -> bool {
        self.emergency_watch_active
    }
    pub fn guardian_pid(&self) -> Option<u32> {
        self.guardian_pid
    }
    pub async fn stop(&mut self) -> Result<()> {
        if self.task.is_finished() {
            return Ok(());
        }
        let (tx, rx) = oneshot::channel();
        if self.stop.send(tx).await.is_err() {
            (&mut self.task).await?;
            return Ok(());
        }
        rx.await.context("等待键鼠引擎退出失败")??;
        (&mut self.task).await.context("等待引擎退出保护回收失败")?;
        Ok(())
    }
}
async fn stop_child(child: &mut Child) -> Result<()> {
    if let Ok(result) = tokio::time::timeout(Duration::from_millis(1500), child.wait()).await {
        result.context("等待引擎退出失败")?;
        return Ok(());
    }
    #[cfg(unix)]
    if let Some(pid) = child.id() {
        unsafe {
            libc::kill(pid as i32, libc::SIGTERM);
        }
    }
    #[cfg(windows)]
    child.start_kill()?;
    if let Ok(result) = tokio::time::timeout(Duration::from_millis(1500), child.wait()).await {
        result.context("等待引擎退出失败")?;
        return Ok(());
    }
    child.kill().await.context("引擎仍未退出，禁止重复启动")?;
    child.wait().await?;
    Ok(())
}
